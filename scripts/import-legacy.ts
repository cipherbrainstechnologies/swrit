import fs from "node:fs";
import path from "node:path";
import { arg, flag, loadEnvFiles } from "./_cli";

loadEnvFiles();

/**
 * Import a local folder of photos/videos and/or ZIP archives through the same
 * validation pipeline as the web uploader. Idempotent: files already in the archive
 * (same SHA-256) are skipped.
 *
 *   pnpm media:import --path ./media-inbox
 *   pnpm media:import --path ./photos/SWrit
 *   pnpm media:import --path ./media-inbox/legacy-films --legacy-films
 *
 * Files inside any folder named `legacy-films` become past editions in the Birthday Theatre.
 * Add --wait to process previews in this process (useful with the local PGlite database).
 */
async function main() {
  const root = arg("path");
  if (!root) throw new Error("Usage: pnpm media:import --path <folder or zip>");
  const abs = path.resolve(root);
  if (!fs.existsSync(abs)) throw new Error(`Not found: ${root}`);

  const { getDb, schema, closeDb } = await import("../src/server/db");
  const { env } = await import("../src/server/env");
  const { getStorage } = await import("../src/server/storage");
  const { ingestLocalFile } = await import("../src/server/media/ingest");
  const { importZipFile } = await import("../src/server/imports/run");
  const db = await getDb();
  const storage = await getStorage();
  const owners = await db.select().from(schema.childProfiles).limit(2);
  if (owners.length !== 1) throw new Error("Run `pnpm owner:bootstrap` first (exactly one child profile is expected).");
  const child = owners[0];
  const ctx = { db, storage, childId: child.id, ownerUserId: child.ownerUserId };
  const maxBytes = env().MAX_UPLOAD_MB * 1024 * 1024;
  const allLegacy = flag("legacy-films");

  const files: string[] = [];
  const walk = (p: string) => {
    const st = fs.lstatSync(p);
    if (st.isSymbolicLink()) return; // never follow links
    if (st.isDirectory()) for (const f of fs.readdirSync(p).sort()) walk(path.join(p, f));
    else if (st.isFile()) files.push(p);
  };
  walk(abs);

  const totals = { accepted: 0, duplicates: 0, rejected: 0 };
  const errors: string[] = [];
  for (const [i, file] of files.entries()) {
    const rel = path.relative(abs, file).replace(/\\/g, "/") || path.basename(file);
    const base = path.basename(file);
    if (base.startsWith(".") || base === "Thumbs.db") continue;
    const legacy = allLegacy || /(^|\/)legacy-films\//i.test(path.relative(process.cwd(), file).replace(/\\/g, "/"));
    if (/\.zip$/i.test(file)) {
      const [imp] = await db
        .insert(schema.imports)
        .values({ ownerUserId: child.ownerUserId, childId: child.id, sourceLabel: base, status: "processing" })
        .returning();
      const r = await importZipFile(ctx, imp.id, file);
      await db.update(schema.imports).set({ status: "ready", finishedAt: new Date() }).where((await import("drizzle-orm")).eq(schema.imports.id, imp.id));
      totals.accepted += r.accepted;
      totals.duplicates += r.duplicates;
      totals.rejected += r.rejected;
      console.log(`[${i + 1}/${files.length}] ZIP ${base}: ${r.accepted} added, ${r.duplicates} already present, ${r.rejected} skipped`);
      continue;
    }
    const r = await ingestLocalFile(ctx, file, { filename: base, sourcePath: rel, isLegacyFilm: legacy, maxBytes });
    if (r.outcome === "accepted") totals.accepted++;
    else if (r.outcome === "duplicate") totals.duplicates++;
    else {
      totals.rejected++;
      errors.push(`${rel}: ${r.reason}`);
    }
    if ((i + 1) % 10 === 0 || i === files.length - 1) process.stdout.write(`\r${i + 1}/${files.length} files scanned`);
  }
  console.log(`\nDone: ${totals.accepted} added, ${totals.duplicates} already in the archive, ${totals.rejected} skipped.`);
  for (const e of errors.slice(0, 50)) console.log(`  skipped ${e}`);

  if (flag("wait")) {
    const { startWorker } = await import("../src/worker/runner");
    const { sql } = await import("drizzle-orm");
    const w = startWorker({ name: "cli-import", pollMs: 300 });
    process.stdout.write("Generating previews");
    for (;;) {
      const r = (await db.execute(sql`select count(*)::int as n from jobs where status in ('queued','processing') and job_type = 'media.process'`)) as unknown;
      const rows = Array.isArray(r) ? r : (r as { rows: { n: number }[] }).rows;
      if (Number(rows[0]?.n ?? 0) === 0) break;
      process.stdout.write(".");
      await new Promise((res) => setTimeout(res, 1500));
    }
    await w.stop();
    console.log(" done.");
  } else {
    console.log("Previews and dates are generated by the worker in the background.");
  }
  await closeDb();
}

main().catch((err) => {
  console.error("Import failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
