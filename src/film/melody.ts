/**
 * Music used when the parent has not uploaded a song.
 *
 * 1. An ORIGINAL warm instrumental bed (simple I–vi–IV–V arpeggios written for this app).
 * 2. The traditional "Happy Birthday to You" MELODY as an instrumental (the melody is in the
 *    public domain). This is always labelled as an instrumental; nothing here is a vocal.
 *
 * Shared by the browser Theatre (Web Audio) and the renderer (PCM synthesis for FFmpeg).
 */

export type Note = { time: number; duration: number; freq: number; gain: number; voice: "lead" | "pad" | "bass" };

export const INSTRUMENTAL_LABEL = "Instrumental music generated by Dear Swritsinh (no vocals)";
export const FINALE_LABEL = "“Happy Birthday to You”: traditional melody, instrumental (no vocals)";

const A4 = 440;
export function midiToFreq(m: number): number {
  return A4 * Math.pow(2, (m - 69) / 12);
}

/** Original arpeggiated bed. Returns notes covering `seconds`. */
export function instrumentalBed(seconds: number, bpm = 84): Note[] {
  const beat = 60 / bpm;
  // C, Am, F, G (root MIDI numbers around C3) with gentle arpeggio patterns.
  const chords = [
    [48, 52, 55, 60],
    [45, 52, 57, 60],
    [41, 48, 53, 57],
    [43, 50, 55, 59],
  ];
  const pattern = [0, 2, 1, 3, 2, 1];
  const notes: Note[] = [];
  let t = 0;
  let bar = 0;
  while (t < seconds) {
    const chord = chords[bar % chords.length];
    notes.push({ time: t, duration: beat * 4, freq: midiToFreq(chord[0] - 12), gain: 0.16, voice: "bass" });
    for (const n of chord.slice(1)) {
      notes.push({ time: t, duration: beat * 4, freq: midiToFreq(n), gain: 0.05, voice: "pad" });
    }
    for (let i = 0; i < pattern.length; i++) {
      const at = t + i * (beat * 4) / pattern.length;
      if (at >= seconds) break;
      notes.push({
        time: at,
        duration: beat * 0.9,
        freq: midiToFreq(chord[pattern[i]] + 12),
        gain: 0.11,
        voice: "lead",
      });
    }
    t += beat * 4;
    bar++;
  }
  return notes.filter((n) => n.time < seconds);
}

/** Traditional melody (public domain), in G major, 3/4. [midi, beats] */
const HB: [number, number][] = [
  [62, 0.75], [62, 0.25], [64, 1], [62, 1], [67, 1], [66, 2],
  [62, 0.75], [62, 0.25], [64, 1], [62, 1], [69, 1], [67, 2],
  [62, 0.75], [62, 0.25], [74, 1], [71, 1], [67, 1], [66, 1], [64, 2],
  [72, 0.75], [72, 0.25], [71, 1], [67, 1], [69, 1], [67, 3],
];
const HB_CHORDS: [number[], number][] = [
  [[43, 47, 50], 3], [[50, 54, 57], 3], [[50, 54, 57], 3], [[43, 47, 50], 3],
  [[43, 47, 50], 3], [[48, 52, 55], 3], [[50, 54, 57], 3], [[43, 47, 50], 3],
];

export function happyBirthdayBeats(): number {
  return HB.reduce((n, [, b]) => n + b, 0);
}

export function happyBirthday(startAt: number, bpm = 96): { notes: Note[]; duration: number } {
  const beat = 60 / bpm;
  const notes: Note[] = [];
  let t = startAt;
  for (const [m, b] of HB) {
    notes.push({ time: t, duration: b * beat * 0.95, freq: midiToFreq(m + 12), gain: 0.2, voice: "lead" });
    t += b * beat;
  }
  // Pickup (two beats) before the first chord.
  let c = startAt + beat;
  for (const [chord, beats] of HB_CHORDS) {
    for (const n of chord) notes.push({ time: c, duration: beats * beat, freq: midiToFreq(n), gain: 0.06, voice: "pad" });
    notes.push({ time: c, duration: beats * beat, freq: midiToFreq(chord[0] - 12), gain: 0.14, voice: "bass" });
    c += beats * beat;
  }
  const end = Math.max(t, c) + beat;
  return { notes, duration: end - startAt };
}

/** Full default score: bed until `finaleStart`, then the melody played twice (≈ 2 × 16 s). */
export function defaultScore(totalSeconds: number, finaleStart: number): { notes: Note[]; finaleSeconds: number } {
  const bed = instrumentalBed(Math.max(0, finaleStart)).filter((n) => n.time + n.duration <= finaleStart + 0.5);
  const first = happyBirthday(finaleStart);
  const second = happyBirthday(finaleStart + first.duration);
  const notes = [...bed, ...first.notes, ...second.notes].filter((n) => n.time < totalSeconds);
  return { notes, finaleSeconds: first.duration * 2 };
}

/** Length of the default finale (two passes of the melody). */
export function defaultFinaleSeconds(): number {
  return happyBirthday(0).duration * 2;
}

/** Render notes into a mono Float32 PCM buffer (used by the server renderer). */
export function synthesize(notes: Note[], seconds: number, sampleRate = 48000): Float32Array {
  const out = new Float32Array(Math.ceil(seconds * sampleRate));
  for (const n of notes) {
    const start = Math.floor(n.time * sampleRate);
    const len = Math.floor(n.duration * sampleRate);
    const attack = Math.min(len, Math.floor((n.voice === "pad" ? 0.25 : 0.01) * sampleRate));
    const release = Math.min(len, Math.floor((n.voice === "pad" ? 0.6 : 0.25) * sampleRate));
    const w = (2 * Math.PI * n.freq) / sampleRate;
    for (let i = 0; i < len + release && start + i < out.length; i++) {
      let env = 1;
      if (i < attack) env = i / attack;
      else if (n.voice === "lead") env = Math.exp(-(i - attack) / (sampleRate * 0.55));
      if (i >= len) env *= Math.max(0, 1 - (i - len) / release);
      const x = w * i;
      // Soft, piano-like timbre: fundamental + a few decaying harmonics.
      const s =
        n.voice === "bass"
          ? Math.sin(x) + 0.25 * Math.sin(2 * x)
          : Math.sin(x) + 0.35 * Math.sin(2 * x) + 0.12 * Math.sin(3 * x) + 0.05 * Math.sin(4 * x);
      out[start + i] += s * env * n.gain;
    }
  }
  // Gentle limiter.
  let peak = 0;
  for (const v of out) peak = Math.max(peak, Math.abs(v));
  const scale = peak > 0.89 ? 0.89 / peak : 1;
  if (scale !== 1) for (let i = 0; i < out.length; i++) out[i] *= scale;
  return out;
}

export function toWav(samples: Float32Array, sampleRate = 48000): Uint8Array {
  const data = new ArrayBuffer(44 + samples.length * 2);
  const v = new DataView(data);
  const w = (o: number, s: string) => [...s].forEach((c, i) => v.setUint8(o + i, c.charCodeAt(0)));
  w(0, "RIFF");
  v.setUint32(4, 36 + samples.length * 2, true);
  w(8, "WAVE");
  w(12, "fmt ");
  v.setUint32(16, 16, true);
  v.setUint16(20, 1, true);
  v.setUint16(22, 1, true);
  v.setUint32(24, sampleRate, true);
  v.setUint32(28, sampleRate * 2, true);
  v.setUint16(32, 2, true);
  v.setUint16(34, 16, true);
  w(36, "data");
  v.setUint32(40, samples.length * 2, true);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    v.setInt16(44 + i * 2, s < 0 ? s * 0x8000 : s * 0x7fff, true);
  }
  return new Uint8Array(data);
}
